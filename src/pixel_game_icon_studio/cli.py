GENERATED_MARKER = "generated by pgs"


def _print_issues(name: str, issues: list[Issue]) -> None:
    for issue in issues:
        print(f"  {issue} [{name}]")


def _write_document(
    path: Path,
    content: str,
    force: bool = False,
    overwrite: bool = False,
) -> tuple[str, str]:
    """写生成文档，返回 (状态, 说明)。

    ``overwrite=True`` 时无条件覆盖同名文件（agents-md 默认行为）；
    否则受 ``force`` 与生成标记保护。
    """
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            return "unchanged", "内容已是最新"
        generated = GENERATED_MARKER in current[:2000]
        if not overwrite and not generated and not force:
            return "skipped", "已存在手写文件，使用 --force 覆盖"
        status = "updated"
    else:
        status = "created"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return status, ""


def _cmd_samples(args: argparse.Namespace) -> int:
    try:
        written = write_samples(args.out)
    except SvgError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1
    for path in written:
        print(f"  {path.as_posix()}")
    print(f"完成: {len(written)} 个示例图标 -> {Path(args.out).as_posix()}/")
    return 0


def _cmd_build(args: argparse.Namespace) -> int:
    try:
        report = build(
            src=args.src,
            out=args.out,
            sizes=args.sizes,
            background=args.bg,
        )
    except SvgError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    for icon in report.icons:
        print(f"[{icon['id']}] {icon['name']} · {icon['rarity']}")
        for size, png in icon["png"].items():
            print(f"  {size:>3}px  OK  {png}")

    problems = {name: issues for name, issues in report.problems.items() if issues}
    if problems:
        print()
        for name, issues in problems.items():
            _print_issues(name, issues)

    failed = report.failed_files
    print()
    print(
        f"完成: {len(report.icons) - len(failed)}/{len(report.icons)} 个图标，"
        f"{report.png_count} 张 PNG -> {Path(args.out).as_posix()}/"
    )
    if report.manifest_path:
        print(f"manifest -> {report.manifest_path.as_posix()}")
    if failed:
        print(f"失败: {len(failed)} 个文件未通过规范校验，详见上方错误", file=sys.stderr)
        return 1
    print("打开预览: uv run pgs serve")
    return 0


def _cmd_check(args: argparse.Namespace) -> int:
    try:
        results = check(args.src)
    except SvgError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    errors = 0
    warnings = 0
    for name, issues in results.items():
        for issue in issues:
            if issue.is_error:
                errors += 1
            else:
                warnings += 1
        if issues:
            print(f"{Path(args.src).as_posix()}/{name}")
            _print_issues(name, issues)

    print()
    print(f"校验完成: {len(results)} 个文件，{errors} 个错误，{warnings} 个警告")
    return 1 if errors else 0


def _cmd_serve(args: argparse.Namespace) -> int:
    from .studio import StudioRequestHandler

    root = Path(args.root).resolve()
    if not (root / "preview.html").is_file():
        print(f"警告: {root} 下没有 preview.html，仍将提供目录浏览", file=sys.stderr)
    handler = partial(
        StudioRequestHandler,
        directory=str(root),
        catalog_dir=str(root / "catalog"),
    )
    try:
        server = ThreadingHTTPServer((args.bind, args.port), handler)
    except OSError as exc:
        print(f"错误: 无法监听 {args.bind}:{args.port} - {exc}", file=sys.stderr)
        return 1

    base = f"http://{args.bind}:{server.server_port}"
    print(f"AGENTS.md 配置页: {base}/studio")
    print(f"图标图库:         {base}/preview.html")
    print(f"根目录:           {root}")
    print("按 Ctrl+C 停止")
    if not args.no_browser:
        webbrowser.open(f"{base}/studio")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n已停止")
    finally:
        server.server_close()
    return 0


def _cmd_install(args: argparse.Namespace) -> int:
    try:
        style = get_style(args.style)
        report = install(
            root=args.root,
            tools=args.tools,
            style=style,
            force=args.force,
            with_mcp=not args.no_mcp,
            dry_run=args.dry_run,
            template=args.template,
            catalog_dir=args.catalog_dir,
            art_style=args.art_style,
            palette=args.palette,
        )
    except (ValueError, InstallError) as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    print(f"风格: {style.name}（{style.key}）")
    if args.dry_run:
        print("模式: dry-run（不写文件）")
    print()
    print(f"{'状态':<10}{'工具':<10}路径")
    print("-" * 72)
    for result in report.results:
        print(f"{result.status:<10}{result.target:<10}{result.path.as_posix()}")
        if result.detail:
            print(f"{'':<20}{result.detail}")
    print("-" * 72)
    print(
        f"完成: 写入 {len(report.written)} 个文件，"
        f"跳过 {len(report.skipped)} 个，其余未变化。"
    )
    if report.skipped:
        print("部分目标已存在手写文件，确认后可加 --force 覆盖。", file=sys.stderr)
        return 1
    return 0


def _catalog_text(template: str, catalog_dir: str, detail: str) -> str | None:
    """按模板加载目录并转 Markdown；目录缺失时返回 None。"""
    kinds = kinds_for_template(template)
    if not kinds:
        return None
    try:
        catalog = load_catalog(catalog_dir, kinds)
    except CatalogError as exc:
        print(f"警告: {exc}；将生成不含图标目录的文档", file=sys.stderr)
        return None
    return catalog.markdown(kinds, detail=detail)


def _design_text(args: argparse.Namespace) -> str | None:
    """加载设计体系并转 Markdown；缺失或参数错误时返回 None。"""
    try:
        system = load_design_system(args.catalog_dir)
        return build_design_markdown(system, args.art_style, args.palette)
    except DesignError as exc:
        print(f"警告: {exc}；将生成不含设计体系的文档", file=sys.stderr)
        return None


def _blueprint_text(template: str, catalog_dir: str, detail: str = "full") -> str | None:
    """按 catalog 分类生成蓝图；目录缺失时回退到内置蓝图。"""
    kinds = kinds_for_template(template)
    if not kinds:
        return None
    try:
        catalog = load_catalog(catalog_dir, kinds)
    except CatalogError:
        return None
    return catalog.blueprint_markdown(kinds, detail=detail)


def _config_markdown(args: argparse.Namespace, style) -> str:
    key = (args.palette or "").strip() or None
    label = None
    if key:
        try:
            system = load_design_system(args.catalog_dir)
            palette = system.find_palette(key)
            label = palette.name if palette else None
        except DesignError:
            pass
    return build_config_table(
        style,
        project_name="图标工厂",
        template_key=args.template,
        art_style=args.art_style,
        palette_key=key,
        palette_label=label,
    )


def _cmd_agents_md(args: argparse.Namespace) -> int:
    style = get_style(args.style)
    out = Path(args.out)
    catalog_markdown = _catalog_text(args.template, args.catalog_dir, "full")
    design_markdown = _design_text(args)
    config_markdown = _config_markdown(args, style)
    blueprint_markdown = _blueprint_text(args.template, args.catalog_dir, "full")
    status, detail = _write_document(
        out,
        agents_document(
            style,
            catalog_markdown=catalog_markdown,
            design_markdown=design_markdown,
            art_style=args.art_style,
            config_markdown=config_markdown,
            blueprint_markdown=blueprint_markdown,
        ),
        force=args.force,
        overwrite=True,
    )
    if status == "skipped":
        print(f"错误: {out.as_posix()} {detail}", file=sys.stderr)
        return 1
    print(f"{status}: {out.as_posix()}（风格 {style.key}，模板 {args.template}）")
    return 0


def _catalog_json(catalog) -> str:
    data = []
    for catalog_file in catalog.files:
        data.append(
            {
                "kind": catalog_file.kind,
                "title": catalog_file.title,
                "description": catalog_file.description,
                "categories": [
                    {
                        "key": category.key,
                        "name": category.name,
                        "description": category.description,
                        "icons": [
                            {
                                "slug": icon.slug,
                                "name": icon.name,
                                "rarity": icon.rarity,
                                "keywords": list(icon.keywords),
                                "silhouette": icon.silhouette,
                                "palette": list(icon.palette),
                                "notes": icon.notes,
                            }
                            for icon in category.icons
                        ],
                    }
                    for category in catalog_file.categories
                ],
            }
        )
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def _print_catalog(catalog, icons, filtered: bool) -> None:
    print(f"{'kind':<8}{'分类':<22}{'图标数':>6}")
    print("-" * 40)
    for catalog_file in catalog.files:
        for category in catalog_file.categories:
            print(f"{catalog_file.kind:<8}{category.name:<22}{len(category.icons):>6}")
    print("-" * 40)
    print(f"总计: {len(catalog.icons)} 个图标（{len(catalog.files)} 个目录文件）")
    if filtered:
        print()
        print(f"{'slug':<24}{'中文名':<14}{'分类':<20}{'稀有度':<9}主色")
        print("-" * 76)
        for icon in icons:
            print(
                f"{icon.slug:<24}{icon.name:<14}{icon.category_name:<20}"
                f"{icon.rarity or '-':<9}{icon.palette[1]}"
            )


def _cmd_catalog(args: argparse.Namespace) -> int:
    kinds = None if args.kind == "all" else [args.kind]
    try:
        catalog = load_catalog(args.catalog_dir, kinds)
    except CatalogError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    icons = catalog.find(kinds=kinds, category=args.category, query=args.search)
    if args.format == "table":
        _print_catalog(catalog, icons, bool(args.category or args.search))
        return 0

    text = _catalog_json(catalog) if args.format == "json" else catalog.csv(kinds)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"已导出: {out.as_posix()}（{len(text.splitlines())} 行）")
    else:
        print(text, end="")
    return 0


def _cmd_coverage(args: argparse.Namespace) -> int:
    kinds = None if args.kind == "all" else [args.kind]
    try:
        report = check_coverage(args.src, args.catalog_dir, kinds)
    except CatalogError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    print(f"覆盖: {report.covered}/{len(report.expected)}")
    for kind, (done, total) in report.counts_by_kind().items():
        print(f"  {kind}: {done}/{total}")
    if report.missing:
        print(f"\n缺少 {len(report.missing)} 个:")
        for item in report.missing:
            print(f"  {item.kind}/{item.category}: {item.name}（`{item.slug}`）")
    if report.extra:
        print(f"\n多余 {len(report.extra)} 个（不在 catalog 中）:")
        for slug in report.extra:
            print(f"  {slug}")
    print(
        "\n完成: "
        + ("全部覆盖" if report.ok else "存在缺失或多余条目，请补齐后重新运行")
    )
    return 0 if report.ok else 1


def _cmd_restyle(args: argparse.Namespace) -> int:
    try:
        report = restyle_icons(
            src=args.src,
            out=args.out,
            style_key=args.style or "classic",
            palette_key=args.palette or None,
            art_style=args.art_style,
            catalog_dir=args.catalog_dir,
            backup=not args.no_backup,
        )
    except RestyleError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    if report.backup:
        print(f"备份: {report.backup.as_posix()}")
    for path in report.written:
        print(f"updated: {path.as_posix()}（{args.art_style} / {args.style or 'classic'}）")
    for problem in report.skipped:
        print(f"skip: {problem}", file=sys.stderr)
    print(
        f"完成: {len(report.written)} 个图标（{args.art_style} 画法）"
        + (f"，{len(report.skipped)} 个跳过" if report.skipped else "")
    )
    return 1 if report.skipped else 0


def _cmd_design(args: argparse.Namespace) -> int:
    try:
        system = load_design_system(args.catalog_dir)
    except DesignError as exc:
        print(f"错误: {exc}", file=sys.stderr)
        return 1

    if args.format == "table":
        print(f"画法风格（{len(system.styles)}）")
        print(f"{'key':<16}{'名称':<18}{'难度':<10}支持")
        print("-" * 58)
        for style in system.styles:
            print(
                f"{style.key:<16}{style.name:<18}{style.difficulty_label:<10}"
                f"{style.supported}"
            )
        print()
        print(f"色板（{len(system.palettes)}）")
        print(f"{'key':<16}{'名称':<24}{'色数':>4}  类型")
        print("-" * 58)
        for palette in system.palettes:
            print(
                f"{palette.key:<16}{palette.name:<24}{palette.size:>4}  {palette.kind}"
            )
        print()
        print(
            f"分类学: 功能层级 {len(system.tiers)} 类 / "
            f"道具 {len(system.item_groups)} 大类 / 题材 {len(system.themes)} 流"
        )
        return 0

    if args.format == "markdown":
        try:
            text = build_design_markdown(system, args.art_style, args.palette)
        except DesignError as exc:
            print(f"错误: {exc}", file=sys.stderr)
            return 1
    else:
        from dataclasses import asdict

        text = json.dumps(
            {
                "styles": [asdict(style) for style in system.styles],
                "palettes": [asdict(palette) for palette in system.palettes],
                "tiers": [asdict(tier) for tier in system.tiers],
                "item_groups": [asdict(group) for group in system.item_groups],
                "themes": [asdict(theme) for theme in system.themes],
            },
            ensure_ascii=False,
            indent=2,
        ) + "\n"

    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"已导出: {out.as_posix()}（{len(text.splitlines())} 行）")
    else:
        print(text, end="")
    return 0


