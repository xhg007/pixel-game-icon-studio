@dataclass
class InstallResult:
    target: str
    path: Path
    status: str  # created | updated | unchanged | skipped | planned
    detail: str = ""


@dataclass
class InstallReport:
    results: list[InstallResult] = field(default_factory=list)

    @property
    def written(self) -> list[InstallResult]:
        return [r for r in self.results if r.status in {"created", "updated"}]

    @property
    def skipped(self) -> list[InstallResult]:
        return [r for r in self.results if r.status == "skipped"]

    @property
    def ok(self) -> bool:
        return not self.skipped


def resolve_tools(selection: str | None) -> list[str]:
    """解析 ``all`` 或 ``claude,cursor`` 形式的工具列表。"""
    if not selection or selection.strip().lower() == "all":
        return list(TOOLS)
    keys: list[str] = []
    for raw in selection.replace(" ", ",").split(","):
        key = raw.strip().lower()
        if not key:
            continue
        if key not in TOOLS:
            options = ", ".join(TOOLS)
            raise InstallError(f"未知工具 {key!r}，可选: all, {options}")
        if key not in keys:
            keys.append(key)
    if not keys:
        raise InstallError("至少选择一个工具，或使用 --tools all")
    return keys


def _frontmatter(fields: tuple[tuple[str, str], ...]) -> str:
    if not fields:
        return ""
    lines = ["---"]
    for key, value in fields:
        if value in {"true", "false"}:
            lines.append(f"{key}: {value}")
            continue
        escaped = value.replace('"', '\\"')
        lines.append(f'{key}: "{escaped}"')
    lines.append("---")
    return "\n".join(lines) + "\n\n"


def render_target(
    target: ToolTarget,
    style: StylePreset,
    catalog_full: str | None = None,
    design_markdown: str | None = None,
    art_style: str | None = None,
    config_markdown: str | None = None,
    blueprint_full: str | None = None,
) -> str:
    body = agents_document(
        style,
        catalog_markdown=catalog_full,
        design_markdown=design_markdown,
        art_style=art_style,
        config_markdown=config_markdown,
        blueprint_markdown=blueprint_full,
    )
    if target.wrapper == "agents":
        return body
    return _frontmatter(
        tuple(
            (key, agent_description(art_style) if key == "description" else value)
            for key, value in target.frontmatter
        )
    ) + body


def _catalog_text(catalog_dir: str | Path | None, template: str, detail: str) -> str | None:
    from .catalog import CatalogError, kinds_for_template, load_catalog

    kinds = kinds_for_template(template)
    if not kinds:
        return None
    directory = Path(catalog_dir) if catalog_dir else Path.cwd() / "catalog"
    try:
        catalog = load_catalog(directory, kinds)
    except CatalogError:
        return None
    return catalog.markdown(kinds, detail=detail)


def _blueprint_text(
    catalog_dir: str | Path | None, template: str, detail: str = "full"
) -> str | None:
    from .catalog import CatalogError, kinds_for_template, load_catalog

    kinds = kinds_for_template(template)
    if not kinds:
        return None
    directory = Path(catalog_dir) if catalog_dir else Path.cwd() / "catalog"
    try:
        catalog = load_catalog(directory, kinds)
    except CatalogError:
        return None
    return catalog.blueprint_markdown(kinds, detail=detail)


def _design_text(
    catalog_dir: str | Path | None,
    art_style: str | None,
    palette: str | None,
) -> str | None:
    from .design import DesignError, design_markdown, load_design_system

    directory = Path(catalog_dir) if catalog_dir else Path.cwd() / "catalog"
    try:
        system = load_design_system(directory)
        return design_markdown(system, art_style, palette)
    except DesignError:
        return None


def _config_text(
    catalog_dir: str | Path | None,
    style: StylePreset,
    template: str,
    art_style: str | None,
    palette: str | None,
) -> str:
    from .design import DesignError, load_design_system

    palette_key = (palette or "").strip() or None
    label = None
    if palette_key:
        directory = Path(catalog_dir) if catalog_dir else Path.cwd() / "catalog"
        try:
            system = load_design_system(directory)
            found = system.find_palette(palette_key)
            label = found.name if found else None
        except DesignError:
            pass
    return build_config_table(
        style,
        project_name="图标工厂",
        template_key=template,
        art_style=art_style,
        palette_key=palette_key,
        palette_label=label,
    )


def _is_generated(path: Path) -> bool:
    try:
        return MARKER in path.read_text(encoding="utf-8")[:2000]
    except OSError:
        return False


def _write_file(path: Path, content: str, force: bool, dry_run: bool) -> InstallResult:
    if path.exists():
        try:
            current = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise InstallError(f"无法读取 {path}: {exc}") from exc
        if current == content:
            return InstallResult("", path, "unchanged", "内容已是最新")
        if not force and not _is_generated(path):
            return InstallResult("", path, "skipped", "已存在非 pgs 生成文件，使用 --force 覆盖")
        status = "updated"
    else:
        status = "created"

    if dry_run:
        return InstallResult("", path, "planned", f"将 {status}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return InstallResult("", path, status)


def _mcp_entry(include_type: bool) -> dict:
    entry: dict = {"command": "uv", "args": ["run", "pgs", "mcp"]}
    if include_type:
        entry = {"type": "stdio", **entry}
    return entry


def _install_mcp(
    root: Path,
    keys: list[str],
    force: bool,
    dry_run: bool,
) -> list[InstallResult]:
    results: list[InstallResult] = []
    selected = set(keys)
    for key, (rel_path, top_key, include_type, owners) in MCP_TARGETS.items():
        if "*" not in owners and not selected.intersection(owners):
            continue
        path = root / rel_path
        entry = _mcp_entry(include_type)
        data: dict = {}
        existed = path.exists()
        if existed:
            try:
                data = json.loads(path.read_text(encoding="utf-8") or "{}")
            except json.JSONDecodeError as exc:
                raise InstallError(f"{rel_path} 不是合法 JSON: {exc}") from exc
            if not isinstance(data, dict):
                raise InstallError(f"{rel_path} 顶层必须是 JSON 对象")
        servers = data.setdefault(top_key, {})
        if not isinstance(servers, dict):
            raise InstallError(f"{rel_path} 的 {top_key} 必须是 JSON 对象")
        if servers.get(MCP_SERVER_NAME) == entry:
            results.append(InstallResult(key, path, "unchanged", "MCP 配置已存在"))
            continue
        if existed and not force:
            # MCP 配置允许安全合并，不覆盖其它 server，因此无需 force
            pass
        servers[MCP_SERVER_NAME] = entry
        if dry_run:
            results.append(InstallResult(key, path, "planned", "将写入 MCP 配置"))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        results.append(
            InstallResult(key, path, "updated" if existed else "created", "MCP 配置")
        )
    return results


def install(
    root: str | Path = ".",
    tools: str | None = "all",
    style: StylePreset | None = None,
    force: bool = False,
    with_mcp: bool = True,
    dry_run: bool = False,
    template: str = "full",
    catalog_dir: str | Path | None = None,
    art_style: str | None = "pixel",
    palette: str | None = None,
) -> InstallReport:
    """按工具矩阵写入技能文件，并生成/合并 MCP 配置。"""
    from .config import get_style

    style = style or get_style()
    root_path = Path(root)
    keys = resolve_tools(tools)
    report = InstallReport()

    catalog_full = _catalog_text(catalog_dir, template, "full")
    design_markdown = _design_text(catalog_dir, art_style, palette)
    config_markdown = _config_text(catalog_dir, style, template, art_style, palette)
    blueprint_full = _blueprint_text(catalog_dir, template, "full")

    seen: set[Path] = set()
    for key in keys:
        target = TOOLS[key]
        file_path = root_path / target.path
        if file_path in seen:
            continue
        seen.add(file_path)
        result = _write_file(
            file_path,
            render_target(
                target,
                style,
                catalog_full=catalog_full,
                design_markdown=design_markdown,
                art_style=art_style,
                config_markdown=config_markdown,
                blueprint_full=blueprint_full,
            ),
            force=force,
            dry_run=dry_run,
        )
        result.target = target.key
        report.results.append(result)

    if with_mcp:
        report.results.extend(_install_mcp(root_path, keys, force=force, dry_run=dry_run))
    return report
