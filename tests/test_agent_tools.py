class InstallerTest(unittest.TestCase):
    def test_install_all_writes_expected_matrix(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            report = install(root=root, tools="all")
            written = {r.path.relative_to(root).as_posix() for r in report.written}
            expected = {
                "CLAUDE.md",
                ".cursor/rules/pixel-game-icon.mdc",
                ".windsurf/rules/pixel-game-icon.md",
                ".github/instructions/pixel-game-icon.instructions.md",
                ".clinerules/pixel-game-icon.md",
                ".kiro/steering/pixel-game-icon.md",
                "GEMINI.md",
                "CODEBUDDY.md",
                "AGENTS.md",
                ".mcp.json",
                ".cursor/mcp.json",
                ".vscode/mcp.json",
                ".codebuddy/mcp.json",
                ".pgs/mcp.json",
            }
            self.assertEqual(written, expected)
            self.assertTrue(report.ok)

    def test_cursor_rule_frontmatter(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            install(root=tmp, tools="cursor", with_mcp=False)
            text = (Path(tmp) / ".cursor/rules/pixel-game-icon.mdc").read_text(encoding="utf-8")
            self.assertTrue(text.startswith("---\n"))
            self.assertIn("globs:", text)
            self.assertIn('"icons/**/*.svg"', text)
            self.assertIn("alwaysApply: false", text)
            self.assertIn("generated by pgs", text)

    def test_install_is_idempotent(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            install(root=tmp, tools="claude,agents")
            second = install(root=tmp, tools="claude,agents")
            self.assertEqual(second.written, [])
            self.assertTrue(all(result.status == "unchanged" for result in second.results))

    def test_handwritten_file_is_protected_without_force(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "CLAUDE.md"
            path.write_text("hand written\n", encoding="utf-8")

            report = install(root=tmp, tools="claude", with_mcp=False)
            self.assertFalse(report.ok)
            self.assertEqual(path.read_text(encoding="utf-8"), "hand written\n")

            forced = install(root=tmp, tools="claude", force=True, with_mcp=False)
            self.assertTrue(forced.ok)
            self.assertIn("# AGENTS.md", path.read_text(encoding="utf-8"))

    def test_mcp_merge_preserves_existing_servers(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            existing = {"mcpServers": {"other": {"command": "node", "args": ["x.js"]}}}
            (root / ".mcp.json").write_text(json.dumps(existing), encoding="utf-8")

            install(root=root, tools="claude")
            data = json.loads((root / ".mcp.json").read_text(encoding="utf-8"))
            self.assertEqual(data["mcpServers"]["other"], existing["mcpServers"]["other"])
            self.assertEqual(
                data["mcpServers"][MCP_SERVER_NAME],
                {"command": "uv", "args": ["run", "pgs", "mcp"]},
            )

    def test_dry_run_writes_nothing(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            report = install(root=tmp, tools="all", dry_run=True)
            self.assertTrue(all(result.status == "planned" for result in report.results))
            self.assertEqual(list(Path(tmp).rglob("*")), [])

    def test_resolve_tools(self) -> None:
        self.assertEqual(len(resolve_tools("all")), 10)
        self.assertEqual(resolve_tools("claude, cursor"), ["claude", "cursor"])
        with self.assertRaises(ValueError):
            resolve_tools("unknown-tool")

    def test_codebuddy_and_reasonix_targets(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            report = install(root=root, tools="codebuddy,reasonix")
            self.assertTrue(report.ok)

            codebuddy_doc = root / "CODEBUDDY.md"
            reasonix_doc = root / "AGENTS.md"
            for path in (codebuddy_doc, reasonix_doc):
                text = path.read_text(encoding="utf-8")
                self.assertIn("# AGENTS.md", text)
                self.assertIn("uv run pgs check", text)

            codebuddy_mcp = json.loads(
                (root / ".codebuddy/mcp.json").read_text(encoding="utf-8")
            )
            self.assertEqual(
                codebuddy_mcp["mcpServers"][MCP_SERVER_NAME]["type"], "stdio"
            )
            # Reasonix 读取项目根 .mcp.json
            reasonix_mcp = json.loads((root / ".mcp.json").read_text(encoding="utf-8"))
            self.assertIn(MCP_SERVER_NAME, reasonix_mcp["mcpServers"])

    def test_vscode_mcp_has_type_field(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            install(root=tmp, tools="copilot")
            data = json.loads((Path(tmp) / ".vscode/mcp.json").read_text(encoding="utf-8"))
            self.assertEqual(data["servers"][MCP_SERVER_NAME]["type"], "stdio")


class McpToolsTest(unittest.TestCase):
    def test_create_list_validate_and_build(self) -> None:
        spec = ICONS["potion_healing"]
        with tempfile.TemporaryDirectory() as tmp:
            created = mcp_server.create_icon(
                "potion_test",
                spec.name,
                spec.rarity,
                list(spec.rows),
                spec.palette,
                src=tmp,
            )
            self.assertTrue(created["ok"], created)
            self.assertTrue(Path(created["path"]).is_file())

            listed = mcp_server.list_icons(tmp)
            self.assertTrue(listed["ok"])
            self.assertEqual(listed["count"], 1)
            self.assertEqual(listed["icons"][0]["name"], spec.name)

            validated = mcp_server.validate_icons(tmp)
            self.assertTrue(validated["ok"])
            self.assertEqual(validated["errors"], [])

            built = mcp_server.build_icons(tmp, str(Path(tmp) / "png"), [32])
            self.assertTrue(built["ok"], built)
            self.assertTrue(Path(built["manifest"]).is_file())
            self.assertEqual(built["png_count"], 1)

    def test_create_icon_rejects_bad_input(self) -> None:
        spec = ICONS["coin_gold"]
        with tempfile.TemporaryDirectory() as tmp:
            bad_rarity = mcp_server.create_icon(
                "coin_bad", "坏币", "mythic", list(spec.rows), spec.palette, src=tmp
            )
            self.assertFalse(bad_rarity["ok"])

            short_rows = mcp_server.create_icon(
                "coin_short", "短币", "common", list(spec.rows[:3]), spec.palette, src=tmp
            )
            self.assertFalse(short_rows["ok"])

            self.assertEqual(mcp_server.list_icons(tmp)["count"], 0)

    def test_create_icon_respects_overwrite(self) -> None:
        spec = ICONS["gem_emerald"]
        args = ("gem_test", spec.name, spec.rarity, list(spec.rows), spec.palette)
        with tempfile.TemporaryDirectory() as tmp:
            self.assertTrue(mcp_server.create_icon(*args, src=tmp)["ok"])
            self.assertFalse(mcp_server.create_icon(*args, src=tmp)["ok"])
            self.assertTrue(mcp_server.create_icon(*args, src=tmp, overwrite=True)["ok"])

    def test_style_guide_and_style_list(self) -> None:
        guide = mcp_server.get_style_guide("neon")
        self.assertIn("# AGENTS.md", guide)
        self.assertIn("#f8d84a", guide)
        self.assertEqual(
            [item["key"] for item in mcp_server.style_list()],
            ["classic", "dark-fantasy", "pastel", "neon"],
        )


class CliAgentTest(unittest.TestCase):
    def test_agents_md_command(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "AGENTS.md"
            with quiet():
                code = main(["agents-md", "--out", str(out), "--style", "dark-fantasy"])
            self.assertEqual(code, 0)
            self.assertIn("暗黑奇幻", out.read_text(encoding="utf-8"))

    def test_install_dry_run_command(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            with quiet():
                code = main(["install", "--root", tmp, "--tools", "cursor", "--dry-run"])
            self.assertEqual(code, 0)
            self.assertFalse((Path(tmp) / ".cursor").exists())

    def test_agents_md_command_overwrites_handwritten_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "AGENTS.md"
            out.write_text("hand written\n", encoding="utf-8")
            with quiet():
                code = main(["agents-md", "--out", str(out)])
            self.assertEqual(code, 0)
            text = out.read_text(encoding="utf-8")
            self.assertIn("# AGENTS.md", text)
            self.assertNotIn("hand written", text)


