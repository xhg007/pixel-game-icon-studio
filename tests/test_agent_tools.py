def quiet() -> contextlib.AbstractContextManager:
    return contextlib.redirect_stdout(io.StringIO())


class ConfigTest(unittest.TestCase):
    def test_all_styles_are_complete(self) -> None:
        self.assertEqual(style_names(), ["classic", "dark-fantasy", "pastel", "neon"])
        for key in style_names():
            preset = get_style(key)
            with self.subTest(style=key):
                self.assertEqual(preset.key, key)
                self.assertEqual(set(preset.rarity), {"common", "fine", "rare", "epic", "legend"})
                self.assertEqual(set(preset.potions), {"red", "green", "blue", "purple"})
                self.assertGreaterEqual(len(preset.materials), 8)
                self.assertTrue(all(len(rgb) == 3 for rgb in preset.materials.values()))

    def test_default_and_unknown_style(self) -> None:
        self.assertEqual(get_style().key, DEFAULT_STYLE)
        with self.assertRaises(ValueError):
            get_style("no-such-style")


